/* ─────────── دکمه‌ها ─────────── */
function helpBtn(key) {
  const b = document.createElement("button");
  b.className = "help-btn";
  b.type = "button";
  b.textContent = "؟ راهنمای این صفحه";
  b.title = "این صفحه و همهٔ پارامترهایش را توضیح می‌دهد";
  b.onclick = () => openHelp(key);
  return b;
}

/* روی صفحهٔ اصلی: یک دکمه کنار عنوانِ هر بخش */
function mountHelpButtons() {
  document.querySelectorAll('section[id^="s-"]').forEach((sec) => {
    if (sec.querySelector(".help-btn")) return;
    const h3 = sec.querySelector("h3");
    if (h3) h3.insertAdjacentElement("afterend", helpBtn(sec.id));
    else sec.prepend(helpBtn(sec.id));
  });
}

/* برای صفحاتِ دیگر (مدیر، ورود، راهنما): یک دکمه در یک مکانِ مشخص */
function mountHelpButtonAt(selector, key) {
  const host = document.querySelector(selector);
  if (!host || host.querySelector(".help-btn")) return;
  host.appendChild(helpBtn(key));
}

/* ─────────── پنجرهٔ راهنما ─────────── */
function openHelp(key) {
  const data = PAGE_HELP[key];
  if (!data) return;
  // راهنماهای پنلِ مدیریت فقط وقتی با شناسهٔ مدیر وارد شده باشیم باز می‌شوند
  if (key === "admin" || key.indexOf("admin-") === 0) {
    const tok = (typeof sessionStorage !== "undefined")
      ? (sessionStorage.getItem("station-admin-token") || "") : "";
    if (!tok) {
      const notice = document.createElement("div");
      notice.id = "help-modal";
      notice.setAttribute("role", "dialog");
      notice.innerHTML =
        '<div class="help-backdrop"></div>' +
        '<div class="help-card" dir="rtl" style="inset:35vh 20vw">' +
          '<div class="help-head"><b>راهنمای پنلِ مدیریت</b>' +
          '<button type="button" class="help-x" title="بستن">×</button></div>' +
          '<p class="help-about" style="padding-bottom:16px">این راهنما فقط برای مدیر است؛ ' +
          'ابتدا با شناسه و رمزِ مدیر به پنل وارد شوید، بعد همین‌جا را باز کنید.</p>' +
        '</div>';
      document.body.appendChild(notice);
      const close = () => closeHelp();
      notice.querySelector(".help-backdrop").onclick = close;
      notice.querySelector(".help-x").onclick = close;
      return;
    }
  }
  closeHelp();
  const wrap = document.createElement("div");
  wrap.id = "help-modal";
  wrap.setAttribute("role", "dialog");
  wrap.innerHTML =
    '<div class="help-backdrop"></div>' +
    '<div class="help-card" dir="rtl">' +
      '<div class="help-head">' +
        '<b>' + data.title + '</b>' +
        '<button type="button" class="help-x" title="بستن">×</button>' +
      '</div>' +
      '<p class="help-about">' + data.about + '</p>' +
      '<div class="help-list">' +
        data.items.map((it) =>
          '<div class="help-item"><b>' + it.name + '</b>' +
          '<p><span>چه کار می‌کند:</span> ' + it.does + '</p>' +
          '<p><span>چه استفاده‌ای دارد:</span> ' + it.use + '</p></div>'
        ).join("") +
      '</div>' +
    '</div>';
  document.body.appendChild(wrap);
  const close = () => closeHelp();
  wrap.querySelector(".help-backdrop").onclick = close;
  wrap.querySelector(".help-x").onclick = close;
  document.addEventListener("keydown", function esc(e) {
    if (e.key === "Escape") { close(); document.removeEventListener("keydown", esc); }
  });
}

function closeHelp() {
  const old = document.getElementById("help-modal");
  if (old) old.remove();
}

