"""پیام‌های معرفی و پیگیری — همان چیزی که باید بفرستی تا اولین جلسه گرفته شود.

چرا جدا از برگهٔ «پیشنهاد» است: آن برگه بعد از جلسه معنا دارد؛ این بسته، پیش از جلسه. چهار
متن آماده می‌سازد (پیام اول، پیام بعد از جواب، تأیید وقت، و پیگیری)، به‌همراه یک اسکریپت تماس
تلفنی و پاسخ چهار مخالفت رایج — همه با نام خودت و نام مخاطب، آمادهٔ کپی.

قاعده‌ای که در متن‌ها سخت‌گیرانه رعایت می‌شود: هیچ وعدهٔ سود، هیچ عدد سود، هیچ فوریت ساختگی،
و هیچ پیوستی در پیام اول. هدفِ پیام اول فقط یک چیز است: **گرفتن نیم‌ساعت وقت**.

اجرا:
    python3 outreach.py --client "نام مخاطب"                 # ساخت بستهٔ پیام‌ها
    python3 outreach.py --client "..." --kind brokerage      # لحن مناسب کارگزاری
    python3 outreach.py --json
"""
from __future__ import annotations

import argparse
import json
import sys
from datetime import datetime, timezone
from pathlib import Path

BASE = Path(__file__).resolve().parent
if str(BASE) not in sys.path:
    sys.path.insert(0, str(BASE))

import reportkit as rk  # noqa: E402

VERSION = "0.1.0"
DATA = BASE / "data"
PACK_MD = DATA / "outreach-pack.md"
PACK_HTML = DATA / "outreach-pack.html"

# لحن‌ها: کدام دسته از مخاطب قرار است این را بخواند
KINDS = {
    "brokerage": "کارگزاری یا شرکت تأمین سرمایه",
    "company": "شرکت غیرمالی (تولیدی، بازرگانی، طلا و ارز)",
    "teacher": "مدرس یا تحلیلگر بازار سرمایه",
    "known": "آشنای خودت که در بازار است",
}

_DIGITS = str.maketrans("0123456789", "۰۱۲۳۴۵۶۷۸۹")


def fa(value) -> str:
    return str(value).translate(_DIGITS)


def messages(client: str = "", *, kind: str = "company", sender: str = "مسعود") -> dict:
    """چهار متن آماده + اسکریپت تماس. هر متن با نام مخاطب و امضای خودت پر می‌شود."""
    who = client.strip()
    tone = KINDS.get(kind, KINDS["company"])
    # خطاب با نام کوچک، فقط وقتی مخاطب «آدم» است؛ برای شرکت و کارگزاری، خطاب سرد و رسمی درست‌تر است
