def audit_strategy(sid: str, rows: list[dict] | None = None) -> dict:
    """برای راهبردهایی که عدد می‌پذیرند، حسابرسی کامل می‌سازد (موتور + دستی + شوک‌ها)."""
    rows = rows if rows is not None else inv.fallback_rows()
    kind = NUMERIC_KINDS.get(sid)
    if not kind:
        return {"ok": False, "detail": "این راهبرد عدد بازار نمی‌گیرد (درآمدی/آموزشی است)."}
    try:
        row = inv._pick(kind, rows)
    except LookupError:
        return {"ok": False, "detail": "داده‌ای برای این راهبرد در اسنپ‌شات نبود."}
    solved = inv.solve(row)
    ladder = inv.ladder_for(row)
    stress = stresser.stress_row(row)
    out = {
        "ok": True, "kind": kind, "given": solved["given"], "formula": solved["formula"],
        "steps": solved["steps"], "answer": solved["answer"], "unit": solved["unit"],
        "checks": solved["checks"], "engine_value": solved["answer_num"],
        "hand_value": (solved["checks"][0]["value"] if solved.get("checks") else None),
        "hand_agrees": all(c.get("agree") for c in solved.get("checks", [])) if solved.get("checks") else None,
        "closing": ladder.get("ladder", []), "verdict": ladder.get("verdict"),
        "fees_pct": ladder.get("fees_pct"), "hurdle_pct": ladder.get("hurdle_pct"),
        "margin_pp": ladder.get("margin_pp"), "survives": ladder.get("survives"),
        "resilience_pct": stress.get("resilience_pct"),
        "first_failure": stress.get("first_failure"),
        "fee_tolerance": stress.get("fee_tolerance"),
        "shocks": stress.get("shocks"),
        "margin_call": stress.get("margin"),
        "extras": solved.get("extras", {}),
    }
    # احتمال مدل‌محور برای راهبردهای اختیاری (با نوسان ضمنی خودِ بازار)
    prob = None
    rate = float(row.get("rate") or inv.HURDLE_DEFAULT)
    if kind == "covered_call" and row.get("premium") and row.get("strike") and row.get("days"):
        iv = implied_vol(float(row["premium"]), float(row["spot"]), float(row["strike"]),
                         float(row["days"]), rate, "call")
        if iv.get("ok"):
            p_under = prob_under(float(row["spot"]), float(row["strike"]), float(row["days"]),
                                 rate, iv["sigma"])
            prob = {"iv": iv, "prob_under_strike_pct": round(p_under * 100, 2),
                    "prob_assigned_pct": round((1 - p_under) * 100, 2),
                    "expected_move": round(expected_move(float(row["spot"]), float(row["days"]),
                                                         iv["sigma"]), 2),
                    "detail": (f"با نوسان ضمنی {iv['sigma_pct']}٪، احتمال مدل‌محور اینکه سهم زیر "
                               f"اعمال بماند (پرمیوم کامل مال شما) ≈{p_under * 100:.1f}٪ و احتمال "
                               f"اعمال‌شدن ≈{(1 - p_under) * 100:.1f}٪ است. این عدد «احتمال "
                               f"ریاضی تحت فرض بلک-شولز» است، نه پیش‌بینی بازار.")}
    elif kind == "basis" and row.get("spot") and row.get("future"):
        iv = None
        prob = {"detail": ("این راهبرد جهت‌دار نیست؛ احتمال «سود/زیان» معنا ندارد. عددش قفل‌شده "
                           "است و ریسک اصلی‌اش مارجین‌کال و نقدشوندگی است.")}
    out["model_probability"] = prob
    return out


def as_percent_table(audits: dict) -> list[dict]:
    """جدول یک‌نگاهی: چه راهبردی، چه عددی، با چه برچسب روش."""
    rows = []
    for s in STRATEGIES:
        a = audits.get(s["id"], {})
        if a.get("ok"):
            unit = (a.get("unit") or "").strip()
            value = f"{a.get('answer')} {unit}".strip()
            if unit in ("بله/نه", "بله یا نه"):
                value = str(a.get("answer"))          # تساوی: فقط «بله» یا «نه»
            method = "قطعی/مدل‌محور (موتور ایستگاه + محاسبهٔ دستی دوم)"
            if a.get("model_probability") and a["model_probability"].get("prob_under_strike_pct"):
                value += (f" · احتمال ماندن زیر اعمال "
                          f"{a['model_probability']['prob_under_strike_pct']}٪")
                method = "قطعی + مدل بلک-شولز (نوسان ضمنی از قیمت بازار)"
        else:
            value, method = "ندارد", "بدون دادهٔ عددی امروز (از منبع یا ورودی شما)"
        rows.append({"id": s["id"], "name": s["name"], "class": s["class"],
                     "value": value, "method": method,
                     "resilience": a.get("resilience_pct"), "survives": a.get("survives"),
                     "closing_count": len(a.get("closing") or s.get("closing") or [])})
    return rows


