def build(*, rows: list[dict] | None = None, write: bool = True) -> dict:
    audits = {}
    for s in STRATEGIES:
        if s["id"] in NUMERIC_KINDS:
            audits[s["id"]] = audit_strategy(s["id"], rows)
    table = as_percent_table(audits)
    doc = {"version": VERSION, "strategies": [{k: v for k, v in s.items()} for s in STRATEGIES],
           "audits": audits, "table": table, "study_path": study_path(),
           "honesty": ("درصدها سه نوع‌اند و برچسب دارند: «قطعی» (قفل‌شده در لحظهٔ ورود)، "
                       "«مدل‌محور» (با نوسان ضمنیِ خودِ بازار و فرض بلک-شولز)، و «نقل‌شده» "
                       "(از منبع با نام). هیچ‌کدام وعدهٔ سود نیست."),
           "md_text": "", "ref_md": "", "index_md": ""}
    doc["md_text"] = to_md(doc)
    doc["ref_md"] = references_md(doc)
    doc["index_md"] = index_md(doc)
    if write:
        OUT.mkdir(parents=True, exist_ok=True)
        LIB_MD.write_text(doc["md_text"], encoding="utf-8")
        REF_MD.write_text(doc["ref_md"], encoding="utf-8")
        INDEX_MD.write_text(doc["index_md"], encoding="utf-8")
        LIB_JSON.write_text(json.dumps(doc, ensure_ascii=False, indent=1), encoding="utf-8")
        GUI_DATA.mkdir(parents=True, exist_ok=True)
        (GUI_DATA / "strategy-library.html").write_text(to_html(doc), encoding="utf-8")
        doc.update({"md": str(LIB_MD), "html": str(GUI_DATA / "strategy-library.html"),
                    "json": str(LIB_JSON), "refs": str(REF_MD), "index": str(INDEX_MD)})
    return doc


