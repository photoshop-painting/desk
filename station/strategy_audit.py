# ----------------------------------------------------------------- نوسان و احتمال
def _N(x: float) -> float:
    """تابع توزیع تجمعی نرمال استاندارد."""
    return 0.5 * (1 + math.erf(x / math.sqrt(2)))


def bs_call(s: float, k: float, days: float, r: float, sigma: float) -> float:
    """قیمت نظری اختیار خرید اروپایی (بلک-شولز)."""
    t = max(days, 0.01) / 365.0
    if s <= 0 or k <= 0 or sigma <= 0:
        return 0.0
    d1 = (math.log(s / k) + (r + sigma * sigma / 2) * t) / (sigma * math.sqrt(t))
    d2 = d1 - sigma * math.sqrt(t)
    return s * _N(d1) - k * math.exp(-r * t) * _N(d2)


def bs_put(s: float, k: float, days: float, r: float, sigma: float) -> float:
    """قیمت نظری اختیار فروش اروپایی (از تساوی پوت-کال — مستقل از کد خرید)."""
    t = max(days, 0.01) / 365.0
    if s <= 0 or k <= 0 or sigma <= 0:
        return 0.0
    d1 = (math.log(s / k) + (r + sigma * sigma / 2) * t) / (sigma * math.sqrt(t))
    d2 = d1 - sigma * math.sqrt(t)
    return k * math.exp(-r * t) * _N(-d2) - s * _N(-d1)


def implied_vol(price: float, s: float, k: float, days: float, r: float, kind: str = "call",
                lo: float = 0.01, hi: float = 12.0) -> dict:
    """نوسان ضمنی را از قیمت خودِ بازار درمی‌آورد (نصف‌کردن بازه).

    اگر قیمت بازار از هر دو سر بازه هم پایین‌تر/بالاتر باشد، صریح گفته می‌شود که عدد
    «از بازه بیرون است» — نه اینکه عدد ساختگی بدهیم.
    """
    f = bs_call if kind == "call" else bs_put
    p_lo, p_hi = f(s, k, days, r, lo), f(s, k, days, r, hi)
    if price <= p_lo:
        return {"ok": False, "detail": f"قیمت بازار ({price:.4f}) از نظری‌ترین حالتِ نوسان کم "
                                       f"({p_lo:.4f}) هم کمتر است؛ نوسان ضمنی در بازه نیست."}
    if price >= p_hi:
        return {"ok": False, "detail": f"قیمت بازار ({price:.4f}) از نظری‌ترین حالتِ نوسان زیاد "
                                       f"({p_hi:.4f}) هم بیشتر است؛ یا دادهٔ ورودی جابه‌جاست یا "
                                       f"قیمت بازار با مدل نمی‌خواند."}
    for _ in range(200):
        mid = (lo + hi) / 2
        pm = f(s, k, days, r, mid)
        if pm < price:
            lo = mid
        else:
            hi = mid
    sigma = (lo + hi) / 2
    check = f(s, k, days, r, sigma)
    return {"ok": True, "sigma": round(sigma, 4), "sigma_pct": round(sigma * 100, 2),
            "model_price": round(check, 4), "market_price": round(price, 4),
            "gap_pct": round((check - price) / price * 100, 3),
            "detail": (f"نوسان ضمنی سالانه ≈ {sigma * 100:.2f}٪ (از قیمت بازار "
                       f"{price:,.4f} و مدل بلک-شولز با نرخ {r * 100:.1f}٪). "
                       f"بازسازی مدل با همین نوسان: {check:,.4f}.")}


def prob_under(s: float, k: float, days: float, r: float, sigma: float) -> float:
    """احتمال مدل‌محور اینکه قیمت در سررسید زیر قیمت اعمال بماند."""
    t = max(days, 0.01) / 365.0
    d2 = (math.log(s / k) + (r - sigma * sigma / 2) * t) / (sigma * math.sqrt(t))
    return _N(-d2)


def expected_move(s: float, days: float, sigma: float) -> float:
    """حرکت مورد انتظار قیمت تا سررسید (یک انحراف معیار)."""
    return s * sigma * math.sqrt(max(days, 0.01) / 365.0)


