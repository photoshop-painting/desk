def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="کتابخانهٔ راهبردها + حسابرسی عددها")
    ap.add_argument("--json", action="store_true")
    ap.add_argument("--no-write", action="store_true")
    a = ap.parse_args(argv)
    doc = build(write=not a.no_write)
    if a.json:
        print(json.dumps({k: v for k, v in doc.items() if not k.endswith("_md")},
                         ensure_ascii=False, indent=1))
        return 0
    print(f"جزوهٔ راهبردها — {len(doc['strategies'])} راهبرد · نسخهٔ {VERSION}")
    for t in doc["table"]:
        print(f"  · {t['name']}: {t['value']} — {t['method'][:52]}"
              + (f" · تاب‌آوری {t['resilience']:.0f}٪" if t["resilience"] is not None else ""))
    print("  جزوه:", doc.get("md"))
    print("  نسخهٔ چاپی:", doc.get("html"))
    print("  منابع:", doc.get("refs"))
    return 0


